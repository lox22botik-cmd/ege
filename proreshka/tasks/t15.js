function build(s, want) {
  let i = 0; const gaps = [];
  const h = s.replace(/\{(нн|н)\}/g, (m, g) => { gaps.push(g); i++; return `<span class="gap">(${i})</span>`; });
  const fill = s.replace(/\{(нн|н)\}/g, (m, g) => `<b>${g}</b>`);
  const ans = gaps.map((g, k) => g === want ? k + 1 : '').join('');
  return { h, fill, ans };
}
